-- Commercial terminal History. This is a read projection, never a queue.
-- It is additive, tenant-scoped and does not make operational rows claimable.
CREATE TABLE IF NOT EXISTS engine_history_items (
  history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id text NOT NULL CHECK (btrim(workspace_id) <> ''),
  source_key text NOT NULL CHECK (btrim(source_key) <> ''),
  universal_item_id bigint,
  marketplace text NOT NULL DEFAULT '',
  title text NOT NULL DEFAULT '',
  thumbnail_url text,
  price_text text,
  category text,
  commercial_status text NOT NULL CHECK (commercial_status IN ('sent','partial','error')),
  total_targets integer NOT NULL DEFAULT 0 CHECK (total_targets >= 0),
  sent_targets integer NOT NULL DEFAULT 0 CHECK (sent_targets >= 0),
  failed_targets integer NOT NULL DEFAULT 0 CHECK (failed_targets >= 0),
  destination_summary text,
  channels text[] NOT NULL DEFAULT '{}',
  finalized_at timestamptz NOT NULL,
  source_origin text,
  error_stage text,
  error_code text,
  error_public_message text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (workspace_id, source_key),
  UNIQUE (history_id, workspace_id),
  CHECK (total_targets = sent_targets + failed_targets),
  CHECK ((commercial_status='sent' AND sent_targets>=1 AND failed_targets=0) OR
    (commercial_status='partial' AND sent_targets>=1 AND failed_targets>=1) OR
    (commercial_status='error' AND sent_targets=0))
);

CREATE TABLE IF NOT EXISTS engine_history_targets (
  history_target_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  history_id bigint NOT NULL,
  workspace_id text NOT NULL CHECK (btrim(workspace_id) <> ''),
  destination_id text NOT NULL CHECK (btrim(destination_id) <> ''),
  destination_name_snapshot text NOT NULL CHECK (btrim(destination_name_snapshot) <> ''),
  target_label_snapshot text NOT NULL CHECK (btrim(target_label_snapshot) <> ''),
  channel text NOT NULL CHECK (channel IN ('whatsapp','telegram','discord')),
  target_key text NOT NULL CHECK (btrim(target_key) <> ''),
  status text NOT NULL CHECK (status IN ('sent','failed')),
  provider_message_id text,
  confirmed_at timestamptz,
  error_stage text,
  error_code text,
  error_public_message text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY (history_id,workspace_id)
    REFERENCES engine_history_items(history_id,workspace_id),
  UNIQUE (history_id,destination_id,target_key),
  CHECK ((status='sent' AND confirmed_at IS NOT NULL AND
      btrim(COALESCE(provider_message_id,''))<>'') OR
    (status='failed' AND confirmed_at IS NULL AND provider_message_id IS NULL))
);

CREATE INDEX IF NOT EXISTS engine_history_items_workspace_finalized_idx
  ON engine_history_items (workspace_id,finalized_at DESC,history_id DESC);
CREATE INDEX IF NOT EXISTS engine_history_items_workspace_status_finalized_idx
  ON engine_history_items
    (workspace_id,commercial_status,finalized_at DESC,history_id DESC);
CREATE INDEX IF NOT EXISTS engine_history_items_workspace_marketplace_finalized_idx
  ON engine_history_items
    (workspace_id,marketplace,finalized_at DESC,history_id DESC);
CREATE INDEX IF NOT EXISTS engine_history_targets_workspace_destination_idx
  ON engine_history_targets (workspace_id,destination_id,history_id);
CREATE INDEX IF NOT EXISTS engine_history_targets_workspace_channel_idx
  ON engine_history_targets (workspace_id,channel,history_id);

